import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

from clio_pipeline.cli import main

HAS_RERUN = importlib.util.find_spec("rerun") is not None
HAS_LEROBOT = importlib.util.find_spec("lerobot") is not None


def _corrupt_line_5(episode_dir):
    frames = episode_dir / "frames.ndjson"
    lines = frames.read_text().splitlines()
    record = json.loads(lines[4])
    record["left"]["joints"] = record["left"]["joints"][:199]
    lines[4] = json.dumps(record)
    frames.write_text("\n".join(lines) + "\n")


def test_validate_passes_a_valid_episode(episode_dir, capsys):
    assert main(["validate", str(episode_dir)]) == 0
    assert "ok" in capsys.readouterr().out


def test_validate_fails_with_the_file_and_line_of_each_issue(episode_dir, capsys):
    _corrupt_line_5(episode_dir)

    assert main(["validate", str(episode_dir)]) == 1
    out = capsys.readouterr().out
    assert "frames.ndjson:5: $.left.joints: expected at least 200 items, got 199" in out


def test_validate_checks_every_episode_under_a_directory(make_default_episode, capsys):
    good = make_default_episode("ep-a")
    bad = make_default_episode("ep-b")
    _corrupt_line_5(bad)

    assert main(["validate", str(good.parent)]) == 1
    out = capsys.readouterr().out
    assert re.search(r"ok\s+.*ep-a", out) and re.search(r"FAIL\s+.*ep-b", out)


def test_validate_rejects_a_directory_without_episodes(tmp_path, capsys):
    assert main(["validate", str(tmp_path)]) == 1
    assert "no meta.json" in capsys.readouterr().err


def test_info_summarizes_duration_steps_mistakes_and_coach_calls(episode_dir, capsys):
    assert main(["info", str(episode_dir)]) == 0
    out = capsys.readouterr().out

    assert "ep-20261024-031502-test" in out
    assert re.search(r"180 frames over 2\.98 s, ~60\.0 fps", out)
    assert re.search(r"left 100%, right 83%", out)
    assert re.search(r"lay-flat\s+0\.10 s\s+0\.90 s\s+coach", out)
    assert re.search(r"pinch-shoulder\s+1\.00 s\s+1\.00 s\s+check", out)
    assert re.search(r"pinch-middle\s+2\.00 s\s+0\.98 s\s+not completed", out)
    assert (
        "1.50 s  pinch-shoulder  wrong_hand (rule): Use your left hand for the shoulder dot." in out
    )
    assert "3 tool calls: advance_step 1, flag_mistake 1, highlight 1" in out
    assert "interrupted, 2/5 steps" in out


def test_info_shows_the_plan_origin_goal_and_step_actions(planned_episode_dir, capsys):
    assert main(["info", str(planned_episode_dir)]) == 0
    out = capsys.readouterr().out

    assert re.search(r"plan\s+generated by gemini-test at 2026-10-24T03:14:00.000Z", out)
    assert re.search(r"goal\s+fold my t-shirt fast", out)
    assert re.search(r"pinch-shoulder\s+\[pinch\]", out)


def test_info_names_a_curated_plan(default_episode, plan, capsys):
    plan["origin"] = {"kind": "curated"}
    default_episode.meta["plan"] = plan

    assert main(["info", str(default_episode.write())]) == 0
    out = capsys.readouterr().out
    assert re.search(r"plan\s+curated", out) and "goal" not in out


@pytest.mark.skipif(not HAS_RERUN, reason="rerun-sdk not installed")
def test_view_saves_an_rrd_file(episode_dir, tmp_path):
    out = tmp_path / "replay.rrd"

    assert main(["view", str(episode_dir), "--save", str(out)]) == 0
    assert out.stat().st_size > 10_000


@pytest.mark.skipif(not HAS_LEROBOT, reason="lerobot not installed")
def test_export_lerobot_writes_a_dataset(episode_dir, tmp_path, capsys):
    out = tmp_path / "dataset"

    code = main(
        [
            "export-lerobot",
            str(episode_dir),
            "--out",
            str(out),
            "--repo-id",
            "clio/t",
            "--fps",
            "15",
        ]
    )

    assert code == 0
    info = json.loads((out / "meta" / "info.json").read_text())
    assert (info["fps"], info["total_frames"], info["total_episodes"]) == (15, 45, 1)
    assert "v3.0" in capsys.readouterr().out


@pytest.mark.skipif(not HAS_LEROBOT, reason="lerobot not installed")
def test_export_lerobot_refuses_an_invalid_episode(episode_dir, tmp_path, capsys):
    _corrupt_line_5(episode_dir)

    code = main(
        ["export-lerobot", str(episode_dir), "--out", str(tmp_path / "d"), "--repo-id", "clio/t"]
    )

    assert code == 1
    assert "frames.ndjson:5" in capsys.readouterr().err
    assert not (tmp_path / "d").exists()


def test_console_script_is_installed(episode_dir):
    clio = Path(sys.executable).parent / "clio"
    result = subprocess.run(
        [str(clio), "validate", str(episode_dir)], capture_output=True, text=True
    )

    assert result.returncode == 0, result.stderr


def test_validate_warns_about_lost_batches_without_failing(episode_dir, capsys):
    (episode_dir / "batches.json").write_text(json.dumps({"received": [0, 2], "gaps": [1]}))

    assert main(["validate", str(episode_dir)]) == 0
    out = capsys.readouterr().out
    assert "warn  batches.json: batch seq 1 never arrived" in out


def test_info_reports_batches_received(episode_dir, capsys):
    (episode_dir / "batches.json").write_text(json.dumps({"received": [0, 2], "gaps": [1]}))

    assert main(["info", str(episode_dir)]) == 0
    assert re.search(r"batches\s+2 of 3 received; missing seq 1", capsys.readouterr().out)
