"""Writes the widget font metrics (src/adapters/render/widgets/font-metrics.ts).

The coach's widgets wrap and measure their own text, so a card knows its height on the first
frame and tests run in Node. troika only rasterises. This reads the four bundled woffs (Inter
400, 500 and 600, Inter Tight 600) and writes, in em: each face's vertical metrics as troika reads
them (OS/2 typo ascender and descender, cap height) and the advance of every code point all four
faces have. Kerning is left out; layout checks widths against 97% of the box instead.

Run from the repo root, then format the result:

    uv run --with fonttools --with brotli python -I apps/headset/scripts/font-metrics.py
    pnpm exec biome check --write apps/headset/src/adapters/render/widgets/font-metrics.ts
"""

from pathlib import Path

from fontTools.ttLib import TTFont

HEADSET = Path(__file__).resolve().parent.parent
FONTSOURCE = HEADSET / "node_modules" / "@fontsource"
OUT = HEADSET / "src" / "adapters" / "render" / "widgets" / "font-metrics.ts"

FACES = {
    "inter400": FONTSOURCE / "inter" / "files" / "inter-latin-400-normal.woff",
    "inter500": FONTSOURCE / "inter" / "files" / "inter-latin-500-normal.woff",
    "inter600": FONTSOURCE / "inter" / "files" / "inter-latin-600-normal.woff",
    "interTight600": FONTSOURCE / "inter-tight" / "files" / "inter-tight-latin-600-normal.woff",
}


def em(value: float, upm: int) -> float:
    return round(value / upm, 5)


def ts_string(text: str) -> str:
    """A single-quoted TypeScript string literal, with everything outside printable ASCII escaped."""
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "'" or ch == "\\":
            out.append("\\" + ch)
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{code:04x}")
    return "'" + "".join(out) + "'"


def main() -> None:
    fonts = {face: TTFont(str(path)) for face, path in FACES.items()}
    cmaps = {face: font.getBestCmap() for face, font in fonts.items()}
    shared = sorted(set.intersection(*(set(cmap) for cmap in cmaps.values())))
    # Control characters have no visible glyph and never reach a widget (cleanText drops them).
    shared = [code for code in shared if code >= 0x20 and not 0x7F <= code < 0xA0]
    chars = "".join(chr(code) for code in shared)

    lines = [
        "// Generated by apps/headset/scripts/font-metrics.py from the bundled woffs: do not edit.",
        "// Regenerate (from the repo root) after a font update, then format it with Biome:",
        "//   uv run --with fonttools --with brotli python -I apps/headset/scripts/font-metrics.py",
        "//   pnpm exec biome check --write apps/headset/src/adapters/render/widgets/font-metrics.ts",
        "",
        "import type { FaceId } from './text-port';",
        "",
        "/** One face's metrics in em, as troika reads them (OS/2 typo ascender and descender). */",
        "export interface FaceMetrics {",
        "  unitsPerEm: number;",
        "  ascender: number;",
        "  descender: number;",
        "  capHeight: number;",
        "  xHeight: number;",
        "  /** Advance per character, for every character in SHARED_CHARS. */",
        "  advances: Readonly<Record<string, number>>;",
        "}",
        "",
        f"/** The {len(shared)} characters every widget face has, in code point order. */",
        f"export const SHARED_CHARS = {ts_string(chars)};",
        "",
        "function advances(widths: readonly number[]): Record<string, number> {",
        "  const out: Record<string, number> = {};",
        "  for (let i = 0; i < SHARED_CHARS.length; i++) out[SHARED_CHARS.charAt(i)] = widths[i] ?? 0;",
        "  return out;",
        "}",
        "",
        "export const FONT_METRICS: Readonly<Record<FaceId, FaceMetrics>> = {",
    ]
    for face, font in fonts.items():
        upm = font["head"].unitsPerEm
        os2 = font["OS/2"]
        hmtx = font["hmtx"]
        cmap = cmaps[face]
        widths = ", ".join(str(em(hmtx[cmap[code]][0], upm)) for code in shared)
        lines += [
            f"  {face}: {{",
            f"    unitsPerEm: {upm},",
            f"    ascender: {em(os2.sTypoAscender, upm)},",
            f"    descender: {em(os2.sTypoDescender, upm)},",
            f"    capHeight: {em(os2.sCapHeight, upm)},",
            f"    xHeight: {em(os2.sxHeight, upm)},",
            f"    advances: advances([{widths}]),",
            "  },",
        ]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(HEADSET.parent.parent)}: {len(shared)} characters")


if __name__ == "__main__":
    main()
